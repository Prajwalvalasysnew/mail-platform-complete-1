// E2E: CANSPAM-06 (compliance implementation plan) — the opt-out mechanism
// must not charge a fee, require a login or account, or collect anything
// beyond what is needed to process the request.
//
// The FTC guidance is specific: a recipient must be able to opt out without
// paying, without providing information other than an email address and opt-out
// preferences, and without taking any step beyond sending a reply email or
// visiting a single page. These tests drive the REAL tracker routes (via the
// exported Fastify instance) rather than asserting on rendered markup by hand,
// so a future change that adds an auth guard or an extra form field to the
// unsubscribe page fails here.

import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { app as tracker } from '@platform/tracker/app';
import { db, encodeMessageIdForUrl, isSuppressed, generateMessageId } from '@platform/shared';
import { seedCustomer, seedVerifiedDomain } from './harness.js';

beforeAll(async () => { await tracker.ready(); });
afterAll(async () => { await tracker.close(); });

/** Insert a delivered commercial message and return its tracker URL segment. */
async function seedMessage(customerId: string, domain: string, to: string) {
  const messageId = generateMessageId(domain);
  await db.insertInto('messages').values({
    message_id: messageId,
    customer_id: customerId,
    to_address: to,
    from_address: `sender@${domain}`,
    subject: 'Monthly promotion',
    status: 'delivered',
    message_class: 'commercial',
  } as any).execute();
  return { messageId, encoded: encodeMessageIdForUrl(messageId) };
}

const recipient = () => `optout-${Date.now()}-${Math.random().toString(36).slice(2, 7)}@example.com`;

describe('CANSPAM-06: opt-out requires no login', () => {
  it('serves the unsubscribe page to a completely unauthenticated request', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const { encoded } = await seedMessage(cust.customerId, domain, recipient());

    // No Authorization header, no cookie, no session of any kind.
    const res = await tracker.inject({ method: 'GET', url: `/u/${encoded}` });

    expect(res.statusCode).toBe(200);
    expect(res.headers['content-type']).toContain('text/html');
    // Not a redirect to a login/signup page.
    expect([301, 302, 303, 307, 308]).not.toContain(res.statusCode);
    expect(res.body.toLowerCase()).not.toContain('sign in');
    expect(res.body.toLowerCase()).not.toContain('log in');
    expect(res.body.toLowerCase()).not.toContain('password');
    expect(res.body.toLowerCase()).not.toContain('create an account');
  });

  it('completes the opt-out unauthenticated and suppresses immediately', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);

    // Fetch the page and use only what it gives the recipient — no credentials.
    const page = await tracker.inject({ method: 'GET', url: `/u/${encoded}` });
    const token = page.body.match(/name="token" value="([^"]+)"/)?.[1];
    expect(token).toBeTruthy();

    const post = await tracker.inject({
      method: 'POST', url: `/u/${encoded}`,
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      payload: `token=${encodeURIComponent(token!)}`,
    });

    expect(post.statusCode).toBe(200);
    expect(await isSuppressed(cust.customerId, to)).toBe(true);
  });

  it('honours the RFC 8058 one-click POST with no page visit at all', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);

    const res = await tracker.inject({
      method: 'POST', url: `/u/${encoded}`,
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      payload: 'List-Unsubscribe=One-Click',
    });

    expect(res.statusCode).toBe(200);
    expect(await isSuppressed(cust.customerId, to)).toBe(true);
  });
});

describe('CANSPAM-06: opt-out collects no unnecessary data', () => {
  it('asks for nothing but a confirmation — no name, address, reason, or survey', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const { encoded } = await seedMessage(cust.customerId, domain, recipient());
    const body = (await tracker.inject({ method: 'GET', url: `/u/${encoded}` })).body;

    // The ONLY input on the page is the anti-CSRF token, which is generated by
    // the platform and requires nothing from the recipient. Any other input
    // would be data collected as a condition of opting out.
    const inputs = [...body.matchAll(/<input[^>]*name="([^"]+)"/gi)].map((m) => m[1]);
    expect(inputs).toEqual(['token']);

    // No free-text or choice controls asking why they are leaving.
    expect(body).not.toMatch(/<textarea/i);
    expect(body).not.toMatch(/<select/i);
    expect(body).not.toMatch(/type=["']?(checkbox|radio)/i);
  });

  it('does not require the recipient to retype their email address', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);
    const body = (await tracker.inject({ method: 'GET', url: `/u/${encoded}` })).body;

    // The address is shown for confirmation, never requested as an entry field.
    expect(body).toContain(to);
    expect(body).not.toMatch(/<input[^>]*type=["']?email/i);
  });
});

describe('CANSPAM-06: opt-out charges no fee', () => {
  it('the opt-out path has no payment step and no cost-bearing language', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);

    const page = await tracker.inject({ method: 'GET', url: `/u/${encoded}` });
    const token = page.body.match(/name="token" value="([^"]+)"/)?.[1];
    const done = await tracker.inject({
      method: 'POST', url: `/u/${encoded}`,
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      payload: `token=${encodeURIComponent(token!)}`,
    });

    for (const body of [page.body, done.body]) {
      expect(body).not.toMatch(/\bfee\b|\bpayment\b|\bcharge\b|\bsubscription required\b/i);
      expect(body).not.toMatch(/\$[0-9]/);
    }

    // Completing the opt-out never touches billing.
    const charged = await db.selectFrom('usage_daily').select('customer_id')
      .where('customer_id', '=', cust.customerId).executeTakeFirst();
    expect(charged).toBeUndefined();
    expect(await isSuppressed(cust.customerId, to)).toBe(true);
  });
});

describe('CANSPAM-06: the opt-out link stays usable', () => {
  it('is idempotent — a second opt-out does not error or undo the first', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);

    for (let i = 0; i < 2; i++) {
      const res = await tracker.inject({
        method: 'POST', url: `/u/${encoded}`,
        headers: { 'content-type': 'application/x-www-form-urlencoded' },
        payload: 'List-Unsubscribe=One-Click',
      });
      expect(res.statusCode, `attempt ${i + 1}`).toBe(200);
    }
    expect(await isSuppressed(cust.customerId, to)).toBe(true);
  });

  it('still refuses a forged POST with no valid token (CSRF), without adding recipient friction', async () => {
    const cust = await seedCustomer();
    const domain = await seedVerifiedDomain(cust.customerId);
    const to = recipient();
    const { encoded } = await seedMessage(cust.customerId, domain, to);

    const res = await tracker.inject({
      method: 'POST', url: `/u/${encoded}`,
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      payload: 'token=forged',
    });

    expect(res.statusCode).toBe(403);
    expect(await isSuppressed(cust.customerId, to)).toBe(false);
  });
});
